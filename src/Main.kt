fun main() {
    // Задание 1: рассчитываем комиссию за перевод
    print("Введите сумму перевода в рублях: ")
    val amount = readln().toDouble()

    // Комиссия составляет 0,75% от суммы, но не может быть меньше 35 рублей
    val commission = maxOf(amount * 0.0075, 35.0)

    // Вычисляем сумму, которая останется после вычета комиссии
    val transferAmount = amount - commission

    println("Сумма перевода с учетом комиссии: $transferAmount₽. Комиссия: $commission₽")


    // Задание 2: выбираем правильную форму слова в зависимости от числа отметок
    print("Введите количество отметок «Понравилось»: ")
    val likes = readln().toInt()

    // Для чисел, оканчивающихся на 1, используем «человеку»,
    // кроме чисел, оканчивающихся на 11 (например, 11, 111)
    val word = if (likes % 10 == 1 && likes % 100 != 11) {
        "человеку"
    } else {
        "людям"
    }

    println("Понравилось $likes $word")


    // Задание 3: рассчитываем скидку на покупку
    print("Какую сумму потратил пользователь?: ")
    var sum = readln().toDouble()

    print("Являетесь ли вы постоянным клиентом? (Y/N) ")
    // Проверяем ответ без учета регистра: подойдут и Y, и y
    val regularCustomer = readln().equals("Y", ignoreCase = true)

    // Применяем скидку в зависимости от суммы покупки:
    // от 10 001 рублей — 5%, от 1 001 до 10 000 рублей — 100 рублей
    when {
        sum >= 10001 -> sum *= 0.95
        sum >= 1001 -> sum -= 100
    }

    // Постоянный клиент получает дополнительную скидку 1%,
    // если первоначальная сумма покупки была не меньше 10 001 рубля
    if (sum >= 10001 && regularCustomer) {
        sum *= 0.99
    }

    println("Сумма покупки с учетом скидок: $sum₽")
}